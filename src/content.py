    out, canva, sub, cur = {}, 0, 0, "0"
    for d in src:
        if "pg" in d:
            label = str(d["pg"])
            if not d.get("extra"):
                cur, sub = label, 0
        elif d.get("extra"):
            sub += 1; label = f"{cur}-{sub}"
        else:
            canva += 1
            while str(canva) in moved:
                canva += 1
            sub = 0; cur = label = str(canva)
        out[label] = d
    return out

